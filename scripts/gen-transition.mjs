#!/usr/bin/env node
// Copies scripts/overlay-transition.mjs to modules/<id>/transition.mjs for every module that shows an entrance / exit transition.
//   node scripts/gen-transition.mjs          writes the copies
//   node scripts/gen-transition.mjs --check  fails if a copy differs from the source
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
import { optionsBlock, settingsBlock } from "./overlay-transition-labels.mjs";

/** module id → its default length (seconds) and the overlay element that gets the two options. */
export const TRANSITION_MODULES = { "sponsor-ticker": { seconds: 0.6, element: "sponsors" }, "ticker-overlay": { seconds: 0.5, element: "banner" }, "alerts-overlay": { seconds: 0.5, element: "alerts" } };

/** The manifest of `id` with the transition settings and element options (re-applied in place, so running twice changes nothing). */
export function withTransitions(manifest, { seconds, element }) {
  const m = structuredClone(manifest);
  if (m.minCore.split(".")[1] < 6) m.minCore = "0.6.0"; // `rare`, `unit`, `step` need core 0.6.0
  const mine = settingsBlock(seconds);
  const keep = m.settings.filter((s) => !mine.some((t) => t.key === s.key));
  const at = keep.findIndex((s) => s.key === "devMode");
  m.settings = at < 0 ? [...keep, ...mine] : [...keep.slice(0, at), ...mine, ...keep.slice(at)];
  const el = m.overlayElements.find((e) => e.id === element);
  const opts = optionsBlock();
  el.options = [...el.options.filter((o) => !opts.some((t) => t.id === o.id)), ...opts];
  return m;
}
export const HEADER = "// COPY of scripts/overlay-transition.mjs — GENERATED by `node scripts/gen-transition.mjs`: do not edit by hand.\n";
const source = readFileSync(join(root, "scripts/overlay-transition.mjs"), "utf8");
export const expected = HEADER + source;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [id, spec] of Object.entries(TRANSITION_MODULES)) {
    const file = join(root, "modules", id, "transition.mjs");
    if (!(existsSync(file) && readFileSync(file, "utf8") === expected)) { if (check) stale.push(file); else writeFileSync(file, expected); }
    const manifestFile = join(root, "modules", id, "module.json");
    const current = readFileSync(manifestFile, "utf8");
    const wanted = JSON.stringify(withTransitions(JSON.parse(current), spec), null, 2) + (current.endsWith("\n") ? "\n" : "");
    if (current !== wanted) { if (check) stale.push(manifestFile); else writeFileSync(manifestFile, wanted); }
  }
  if (stale.length) { console.error(`Out of date (run node scripts/gen-transition.mjs):\n- ${stale.join("\n- ")}`); process.exit(1); }
}
